import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { fileURLToPath,pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
// Root marked this eight-CSV create operation once before this builder ran.
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const navDir=path.join(root,'历史净值');
const tmp=path.resolve(root,'../../公共资料/工具/tmp/nav_csv_2026-10-18');
const require=createRequire(path.join(tmp,'entry.mjs'));
const {Workbook}=await import(pathToFileURL(require.resolve('@oai/artifact-tool')).href);
const input=path.join(navDir,'270023_全部历史净值_截至2026-10-15.json');
const output=input.replace(/\.json$/,'.csv');
const bytes=await fs.readFile(input),doc=JSON.parse(bytes);
const headers=['净值日期','单位净值','累计净值','官网单位净值日增长率（%）','基金代码','份额类别'];
assert.equal(doc.count,doc.rows.length);assert.equal(doc.count,3893);
const last=doc.count+1;
const wb=Workbook.create(),sheet=wb.worksheets.add('270023');
sheet.showGridLines=false;
const values=doc.rows.map(r=>[r.date,r.nav,r.accumulated_nav,r.daily_growth_pct,doc.code,doc.share_class]);
sheet.getRange(`A1:F${last}`).values=[headers,...values];
sheet.getRange(`A1:F${last}`).format.font={name:'Arial',size:10};
sheet.getRange(`A1:F${last}`).format.verticalAlignment='center';
sheet.getRange(`A2:A${last}`).setNumberFormat('@');
sheet.getRange(`B2:C${last}`).setNumberFormat('0.0000');
sheet.getRange(`D2:D${last}`).setNumberFormat('0.00');
sheet.getRange(`E2:F${last}`).setNumberFormat('@');
sheet.getRange('A1:F1').format={fill:'#1F4E78',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},horizontalAlignment:'center',verticalAlignment:'center'};
sheet.getRange(`A1:C${last}`).format.columnWidth=15;
sheet.getRange(`D1:D${last}`).format.columnWidth=34;
sheet.getRange(`E1:F${last}`).format.columnWidth=13;
sheet.freezePanes.freezeRows(1);
wb.recalculate();
const inspection=await wb.inspect({kind:'table',range:'270023!A1:F4',include:'values',maxChars:1200,tableMaxRows:4,tableMaxCols:6});
const errors=await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!|#SPILL!|#CALC!',options:{useRegex:true,maxResults:20},maxChars:1200});
const readback=sheet.getRange(`A2:F${last}`).values;
assert.deepEqual(readback,values,'Typed workbook values differ from public official JSON');
// Preserve the established CSV precision and representation. Official raw
// responses retain the exact source strings, JSON retains normalized numbers.
const serialized=readback.map(r=>[r[0],r[1].toFixed(4),r[2].toFixed(4),String(r[3]??''),r[4],r[5]]);
const cell=v=>/[",\r\n]/.test(v)?'"'+v.replaceAll('"','""')+'"':v;
const text='\uFEFF'+[headers,...serialized].map(r=>r.map(cell).join(',')).join('\r\n')+'\r\n';
const preview=await wb.render({sheetName:'270023',range:'A1:F4',scale:1,format:'png'});
const previewPath=path.join(tmp,'public_nav_csv_preview_270023_2026-10-15.png');
await fs.writeFile(previewPath,new Uint8Array(await preview.arrayBuffer()));
await fs.writeFile(output,text,{encoding:'utf8',flag:'wx'});
const saved=await fs.readFile(output);
assert.ok(saved.subarray(0,3).equals(Buffer.from([0xEF,0xBB,0xBF])));
const csv=await Workbook.fromCSV(saved.toString('utf8').replace(/^\uFEFF/,''),{sheetName:'CSVCheck'});
const imported=csv.worksheets.getItemAt(0).getRange(`A1:F${last}`).values;
assert.deepEqual(imported[0],headers);
for(let i=0;i<serialized.length;i++)assert.deepEqual(imported[i+1].map(v=>v===null||v===undefined?'':String(v)),serialized[i],`Round trip mismatch row ${i+2}`);
const report={code:doc.code,count:doc.count,first_date:doc.first_date,last_date:doc.last_date,csv_file:output,json_sha256:crypto.createHash('sha256').update(bytes).digest('hex'),csv_sha256:crypto.createHash('sha256').update(saved).digest('hex'),all_rows_fields_roundtrip_verified:true,utf8_bom:true,existing_schema_preserved:true,preview_file:previewPath,inspection:inspection.ndjson,formula_error_scan:errors.ndjson};
await fs.writeFile(path.join(navDir,'原始数据/全历史分页复核_2026-10-18/270023_CSV读回逐行核验_2026-10-18.json'),JSON.stringify(report,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify(report,null,2));
